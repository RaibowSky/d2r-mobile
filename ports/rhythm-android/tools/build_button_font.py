"""Original, geometric button-symbol adaptation; no platform font outlines used.

PUA assignments follow controller prompts; glyph art is this project's own.
Build dependency: fonttools. Runtime still uses the original SDK font renderer.
"""
from pathlib import Path
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
import io, json, hashlib, math

ROOT=Path(__file__).resolve().parent.parent
PATTERNS={
 'A':['010','101','111','101','101'], 'B':['110','101','110','101','110'],
 'X':['101','101','010','101','101'], 'Y':['101','101','010','010','010'],
 'L':['100','100','100','100','111'], 'R':['110','101','110','101','101'],
 'Z':['111','001','010','100','111'], 'S':['111','100','111','001','111'],
 '+':['000','010','111','010','000'], '-':['000','000','111','000','000'],
 'U':['010','111','010','010','010'], 'D':['010','010','010','111','010'],
 '<':['001','010','100','010','001'], '>':['100','010','001','010','100']}
LABELS={0xe0e0:'A',0xe0e1:'B',0xe0e2:'X',0xe0e3:'Y',0xe0e4:'L',0xe0e5:'R',
        0xe0e6:'ZL',0xe0e7:'ZR',0xe0e8:'SL',0xe0e9:'SR',0xe0eb:'U',0xe0ec:'D',
        0xe0ed:'<',0xe0ee:'>',0xe0ef:'+',0xe0f0:'-',0xe0f1:'+',0xe0f2:'-'}
LABELS.update({0xe0a0+i:label for i,label in enumerate(['A','B','X','Y','L','R','ZL','ZR','SL','SR'])})
LABELS.update({0xe0b3:'+',0xe0b4:'-',0xe111:'U',0xe112:'D',0xe113:'<',0xe114:'>'})

def polygon(pen,points):
    pen.moveTo(points[0])
    for point in points[1:]:pen.lineTo(point)
    pen.closePath()

def symbol(label):
    pen=TTGlyphPen(None)
    # Ring and block-letter contours have opposite winding to keep holes clear.
    for radius,reverse in [(450,False),(395,True)]:
        points=[(round(500+radius*math.cos(i*math.tau/64)),round(350+radius*math.sin(i*math.tau/64))) for i in range(64)]
        polygon(pen,points[::-1] if reverse else points)
    cell=76 if len(label)==1 else 55
    width=(4*len(label)-1)*cell;start=500-width/2
    for n,char in enumerate(label):
        for row,bits in enumerate(PATTERNS[char]):
            for col,bit in enumerate(bits):
                if bit=='1':
                    x=round(start+(4*n+col)*cell);y=round(350+(1.5-row)*cell)
                    polygon(pen,[(x,y),(x,y+cell),(x+cell,y+cell),(x+cell,y)])
    return pen.glyph()

def main():
    glyphs={'.notdef':TTGlyphPen(None).glyph()}
    for code,label in LABELS.items():glyphs[f'uni{code:04X}']=symbol(label)
    fb=FontBuilder(1000,isTTF=True);fb.setupGlyphOrder(list(glyphs));fb.setupCharacterMap({k:f'uni{k:04X}' for k in LABELS})
    fb.setupGlyf(glyphs);fb.setupHorizontalMetrics({name:(1000,0) for name in glyphs})
    fb.setupHorizontalHeader(ascent=850,descent=-150)
    fb.setupNameTable({'familyName':'Rhythm Button Symbols','styleName':'Regular','uniqueFontIdentifier':'RhythmButtonSymbols-1',
                       'fullName':'Rhythm Button Symbols','psName':'RhythmButtonSymbols','version':'Version 1.0'})
    fb.setupOS2(sTypoAscender=850,sTypoDescender=-150,usWinAscent=850,usWinDescent=150)
    fb.setupPost();fb.setupMaxp();fb.font['head'].created=fb.font['head'].modified=2082844800
    fb.font.recalcTimestamp=False;output=io.BytesIO();fb.font.save(output);data=output.getvalue()
    check=TTFont(io.BytesIO(data));assert set(check.getBestCmap())==set(LABELS)
    dest=ROOT/'dm/android/generated';dest.mkdir(exist_ok=True)
    (dest/'rhythm-button-symbols.ttf').write_bytes(data)
    header='/* Generated by .tools/build_rhythm_button_font.py; original project glyphs. */\nstatic const unsigned char rhythm_button_font[]={\n'
    header+='\n'.join(','.join(f'0x{x:02x}' for x in data[i:i+20])+',' for i in range(0,len(data),20))+'\n};\n'
    (dest/'rhythm_button_font.h').write_text(header,encoding='ascii')
    (dest/'rhythm-button-symbols.json').write_text(json.dumps({'sha256':hashlib.sha256(data).hexdigest(),'bytes':len(data),
        'source':'Original project geometric artwork; Android adaptation, not original platform font',
        'mapping_reference':'https://gist.github.com/offalynne/74445027027fc8dd0e789ba42f143470',
        'glyphs':{f'{c:04x}':s for c,s in sorted(LABELS.items())}},indent=2)+'\n')
    print(f'PASS original symbol font: {len(LABELS)} mapped glyphs, {len(data)} bytes')

if __name__=='__main__':main()
